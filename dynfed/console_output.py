"""Concise, stable terminal presentation for research runs.

Does not change selection, optimization, privacy accounting or CSV outputs.
Keep full numerical diagnostics in full_dynfl/round_metrics.csv.
"""
from __future__ import annotations

from collections.abc import Mapping


def format_run_header(*, policy: str, dataset: str, model: str, clients: int,
                      rounds: int, selection_period: int, local_epochs: int,
                      step_limit: int | None, learning_rate: float, device: str,
                      privacy_unit: str, he_execution: str) -> str:
    cap = "none" if step_limit is None else str(step_limit)
    return (f"[RUN] policy={policy} dataset={dataset}/{model} clients={clients} "
            f"rounds={rounds} P={selection_period} lr={learning_rate:g} "
            f"local_epochs={local_epochs} step_cap={cap} device={device} "
            f"privacy_unit={privacy_unit} HE={he_execution}"
            + (" [NOTE: local_epochs are capped by step_cap]" if step_limit is not None else ""))


def format_round_summary(*, policy: str, round_number: int, total_rounds: int,
                         accuracy: float, train_loss: float, test_loss: float,
                         optimizer_steps: int, skipped_clients: int,
                         modes: Mapping[str, int], round_wall_time_sec: float,
                         privacy_unit: str, he_execution: str) -> str:
    mode_summary = ",".join(
        f"{name}:{count}" for name, count in sorted(modes.items(), key=lambda item: (-item[1], item[0]))
    ) or "none"
    return (f"[ROUND] {round_number:03d}/{total_rounds:03d} {policy} "
            f"acc={accuracy:.2%} train_loss={train_loss:.4f} test_loss={test_loss:.4f} "
            f"steps={optimizer_steps} skip={skipped_clients} "
            f"modes={mode_summary} wall={round_wall_time_sec:.1f}s "
            f"privacy={privacy_unit} HE={he_execution}")


# Display-only output router: all normal Python stdout goes into the run log.
# Only [RUN] and [ROUND] data generated by format_* are shown in compact mode.
# Errors on stderr remain visible. The numerical training path is untouched.
import contextlib
import re
import sys
from pathlib import Path
from typing import TextIO


def _parse_items(line: str) -> dict[str, str]:
    return dict(re.findall(r"([A-Za-z_]+)=([^\s]+)", line))


class TrainingConsoleRouter:
    """A line-buffered stdout proxy; safe for fragmented print() writes."""

    def __init__(self, terminal: TextIO, logfile: TextIO, mode: str = "compact"):
        if mode not in ("compact", "verbose", "quiet"):
            raise ValueError(f"unsupported console mode: {mode}")
        self.terminal = terminal
        self.logfile = logfile
        self.mode = mode
        self.buffer = ""
        self.showed_table = False
        self.last_policy = None

    def write(self, text: str) -> int:
        if not isinstance(text, str):
            text = str(text)
        self.logfile.write(text)
        if self.mode == "verbose":
            self.terminal.write(text)
        elif self.mode == "compact":
            self.buffer += text
            while "\n" in self.buffer:
                line, self.buffer = self.buffer.split("\n", 1)
                self._show_line(line)
        return len(text)

    def flush(self) -> None:
        self.logfile.flush()
        if self.mode == "verbose":
            self.terminal.flush()
        elif self.mode == "compact":
            # Do not flush partial lines to screen; print() may call write multiple times.
            self.terminal.flush()

    def isatty(self) -> bool:
        return False

    @property
    def encoding(self):
        return getattr(self.terminal, "encoding", "utf-8")

    def _show_line(self, line: str) -> None:
        if line.startswith("[RUN] "):
            self._show_run(line)
        elif line.startswith("[ROUND] "):
            self._show_round(line)

    def _show_run(self, line: str) -> None:
        items = _parse_items(line)
        policy = items.get("policy", "experiment")
        self.last_policy = policy
        self.showed_table = False
        first_line = (
            "\n  DynFL  |  {dataset}  |  {policy}\n"
            .format(dataset=items.get("dataset", "dataset/model"), policy=policy)
        )
        second_line = (
            "  {clients} clients   P={period}   lr={lr}   epochs={epochs}"
            "   step_cap={cap}   device={device}\n"
            .format(clients=items.get("clients", "-"), period=items.get("P", "-"),
                    lr=items.get("lr", "-"), epochs=items.get("local_epochs", "-"),
                    cap=items.get("step_cap", "-"), device=items.get("device", "-"))
        )
        self.terminal.write(first_line + second_line)
        self.terminal.flush()

    def _show_round(self, line: str) -> None:
        items = _parse_items(line)
        head = line.split()
        rd = head[1] if len(head) > 1 else "?"
        if not self.showed_table:
            self.terminal.write(
                "  " + "-" * 74 + "\n"
                "  Round      Acc     Train loss   Test loss   Steps   Skip    Wall\n"
                "  " + "-" * 74 + "\n"
            )
            self.showed_table = True
        self.terminal.write(
            "  {round:<9} {acc:>7} {train:>13} {test:>11}"
            " {steps:>7} {skip:>6} {wall:>8}\n".format(
                round=rd,
                acc=items.get("acc", "-"), train=items.get("train_loss", "-"),
                test=items.get("test_loss", "-"), steps=items.get("steps", "-"),
                skip=items.get("skip", "-"), wall=items.get("wall", "-"),
            )
        )
        self.terminal.flush()

    def finish(self) -> None:
        if self.mode == "compact" and self.buffer:
            self._show_line(self.buffer)
            self.buffer = ""
        self.logfile.flush()
        if self.mode == "compact" and self.showed_table:
            self.terminal.write("  " + "-" * 74 + "\n")
            self.terminal.flush()


@contextlib.contextmanager
def managed_training_console(mode: str, log_path: str | Path):
    """Route legacy stdout to a UTF-8 audit log; keep errors on stderr visible.

    Use around the training entrypoint (not around argument parsing); verbose
    prints everything, compact prints only table, quiet only logs to disk.
    """
    target = Path(log_path)
    target.parent.mkdir(parents=True, exist_ok=True)
    original = sys.stdout
    with target.open("w", encoding="utf-8", buffering=1) as details:
        router = TrainingConsoleRouter(original, details, mode)
        try:
            with contextlib.redirect_stdout(router):
                yield router
        finally:
            router.finish()
